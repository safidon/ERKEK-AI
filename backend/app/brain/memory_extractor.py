import re


def extract_memory(message: str) -> dict:
    """
    Пайдаланушы хабарламасынан тұрақты ақпаратты шығарады.

    Қайтаратын өрістер:
    - age
    - marital_status
    - children
    - career
    - financial_status
    - main_goal
    - goals
    - habits
    - important_events

    current_problem бұл жерде қайтарылмайды,
    себебі ол тұрақты Memory емес.
    """

    memory = {}

    text = message.strip().lower()

    # =====================================================
    # 1. ЖАС
    # =====================================================

    age_patterns = [
        r"(\d{1,2})\s*жастамын",
        r"жасым\s*(\d{1,2})",
        r"маған\s*(\d{1,2})\s*жас",
        r"(\d{1,2})\s*жасқа\s*толдым",
        r"мне\s*(\d{1,2})\s*лет",
        r"мне\s*(\d{1,2})",
    ]

    for pattern in age_patterns:

        match = re.search(pattern, text)

        if match:
            age = int(match.group(1))

            if 14 <= age <= 100:
                memory["age"] = age
                break

    # =====================================================
    # 2. ОТБАСЫЛЫҚ ЖАҒДАЙ
    # =====================================================

    if any(
        phrase in text
        for phrase in [
            "ажырасқанмын",
            "ажырастым",
            "ажырасып кеттім",
            "ажырасқаныма",
            "разведен",
            "развелся",
            "развелись",
        ]
    ):
        memory["marital_status"] = "ажырасқан"

    elif any(
        phrase in text
        for phrase in [
            "үйленгенмін",
            "үйлендім",
            "әйелім бар",
            "женат",
        ]
    ):
        memory["marital_status"] = "үйленген"

    elif any(
        phrase in text
        for phrase in [
            "бойдақпын",
            "бойдақ",
            "үйленбегенмін",
            "холост",
        ]
    ):
        memory["marital_status"] = "бойдақ"

    # =====================================================
    # 3. БАЛАЛАР
    # =====================================================

    children_patterns = [
        r"(\d+)\s*балам\s*бар",
        r"(\d+)\s*балам",
        r"балаларым\s*(\d+)",
        r"балам\s*(\d+)",
    ]

    for pattern in children_patterns:

        match = re.search(pattern, text)

        if match:
            children = int(match.group(1))

            if 1 <= children <= 20:
                memory["children"] = children
                break

    # Сөзбен жазылған сандар
    number_words = {
        "бір": 1,
        "екі": 2,
        "үш": 3,
        "төрт": 4,
        "бес": 5,
        "алты": 6,
        "жеті": 7,
        "сегіз": 8,
        "тоғыз": 9,
        "он": 10,
    }

    if "children" not in memory:

        for word, number in number_words.items():

            patterns = [
                f"{word} балам бар",
                f"{word} балам",
                f"{word} баламын",
            ]

            if any(pattern in text for pattern in patterns):
                memory["children"] = number
                break

    # Маңызды:
    # "балаларым бар" дегеннен нақты санды ойдан шығармаймыз.

    # =====================================================
    # 4. ЖҰМЫС / МАНСАП
    # =====================================================

    career_patterns = [
        (
            [
                "жұмысым тұрақсыз",
                "жұмыс тұрақсыз",
                "жұмысым тұрақты емес",
                "тұрақсыз жұмыс",
            ],
            "жұмысы тұрақсыз",
        ),

        (
            [
                "жұмыссызбын",
                "жұмыс жоқ",
                "жұмыссыз жүрмін",
                "без работы",
                "безработный",
            ],
            "жұмыссыз",
        ),

        (
            [
                "өз бизнесім бар",
                "бизнесім бар",
                "кәсібім бар",
                "свой бизнес",
            ],
            "кәсіпкер",
        ),
    ]

    for phrases, value in career_patterns:

        if any(phrase in text for phrase in phrases):
            memory["career"] = value
            break

    # =====================================================
    # 5. ҚАРЖЫЛЫҚ ЖАҒДАЙ
    # =====================================================

    financial_patterns = [
        (
            [
                "ақша жетпейді",
                "ақшам жетпейді",
                "қаржы жетпейді",
                "қаржылық қиындық",
                "финансовые проблемы",
            ],
            "қаржылық қиындық бар",
        ),

        (
            [
                "қарызым бар",
                "қарыздарым бар",
                "несием бар",
                "кредитім бар",
                "у меня кредит",
                "у меня долги",
            ],
            "қарызы/несиесі бар",
        ),

        (
            [
                "ақшам жоқ",
                "ақша жоқ",
                "денег нет",
            ],
            "ақша тапшылығы",
        ),
    ]

    for phrases, value in financial_patterns:

        if any(phrase in text for phrase in phrases):
            memory["financial_status"] = value
            break

    # =====================================================
    # 6. НЕГІЗГІ МАҚСАТ
    # =====================================================

    goal_patterns = [
        (
            [
                "балаларыммен қарым-қатынасты қалпына келтіру",
                "балаларыммен қарым-қатынасымды қалпына келтіру",
                "балаларыммен қайта жақындасу",
            ],
            "балаларымен қарым-қатынасты қалпына келтіру",
        ),

        (
            [
                "жұмысымды тұрақтандыру",
                "жұмысымды тұрақты ету",
                "тұрақты жұмыс табу",
            ],
            "жұмысын тұрақтандыру",
        ),

        (
            [
                "ақша тапқым келеді",
                "көбірек ақша тапқым келеді",
                "табысымды көбейткім келеді",
                "көбірек табыс тапқым келеді",
            ],
            "табысын көбейту",
        ),

        (
            [
                "бизнес бастағым келеді",
                "бизнес бастау",
                "кәсіп бастағым келеді",
                "өз бизнесімді бастағым келеді",
            ],
            "бизнес бастау",
        ),
    ]

    for phrases, value in goal_patterns:

        if any(phrase in text for phrase in phrases):
            memory["main_goal"] = value
            break

    # =====================================================
    # 7. ҚОСЫМША МАҚСАТТАР
    # =====================================================

    goals = []

    if any(
        phrase in text
        for phrase in [
            "өзімді дамыту",
            "өзімді дамытқым келеді",
            "саморазвитие",
        ]
    ):
        goals.append("өзін дамыту")

    if any(
        phrase in text
        for phrase in [
            "спортпен айналысамын",
            "спортпен айналысқым келеді",
            "спортқа барғым келеді",
        ]
    ):
        goals.append("дене дайындығын жақсарту")

    if goals:
        memory["goals"] = goals

    # =====================================================
    # 8. ӘДЕТТЕР
    # =====================================================

    habits = []

    if any(
        phrase in text
        for phrase in [
            "спортпен айналысамын",
            "спортпен айналысып жүрмін",
            "спортқа барып жүрмін",
        ]
    ):
        habits.append("спорт")

    if any(
        phrase in text
        for phrase in [
            "ерте тұрамын",
            "ерте тұрып жүрмін",
        ]
    ):
        habits.append("ерте тұру")

    if any(
        phrase in text
        for phrase in [
            "жаттығу жасаймын",
            "жаттығу жасап жүрмін",
            "тренировка жасаймын",
        ]
    ):
        habits.append("жаттығу")

    if habits:
        memory["habits"] = habits

    # =====================================================
    # 9. МАҢЫЗДЫ ОҚИҒАЛАР
    # =====================================================

    important_events = []

    if any(
        phrase in text
        for phrase in [
            "ажырасқаныма",
            "ажырасып кеттім",
            "ажырасып жатырмын",
        ]
    ):
        important_events.append("ажырасу кезеңі")

    if any(
        phrase in text
        for phrase in [
            "жаңа жұмысқа кірдім",
            "жаңа жұмыс таптым",
        ]
    ):
        important_events.append("жаңа жұмыс басталды")

    if important_events:
        memory["important_events"] = important_events

    # =====================================================
    # 10. НӘТИЖЕ
    # =====================================================

    return memory