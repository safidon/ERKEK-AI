import re


KZ_NUMBER_WORDS = {
    "бір": 1,
    "екі": 2,
    "үш": 3,
    "төрт": 4,
    "бес": 5,
    "алты": 6,
    "жеті": 7,
    "сегіз": 8,
    "тоғыз": 9,
    "он": 10,
}

RU_NUMBER_WORDS = {
    "один": 1,
    "одна": 1,
    "двое": 2,
    "два": 2,
    "две": 2,
    "трое": 3,
    "три": 3,
    "четверо": 4,
    "четыре": 4,
    "пятеро": 5,
    "пять": 5,
}


def extract_memory(message: str) -> dict:
    """
    Пайдаланушы хабарламасынан тұрақты ақпаратты шығарады.

    Қайтаратын өрістер:
    - age
    - marital_status
    - children
    - career
    - financial_status
    - main_goal
    - goals
    - habits
    - important_events

    current_problem бұл жерде сақталмайды,
    себебі ол уақытша контекст.
    """

    memory = {}

    text = message.strip().lower()

    # =====================================================
    # 1. ЖАС
    # =====================================================

    age_patterns = [
        r"\b(\d{1,2})\s*жастамын\b",
        r"\bжасым\s*(\d{1,2})\b",
        r"\bмаған\s*(\d{1,2})\s*жас\b",
        r"\b(\d{1,2})\s*жасқа\s*толдым\b",
        r"\bмне\s*(\d{1,2})\s*лет\b",
        r"\bмне\s*(\d{1,2})\s*года\b",
        r"\bмне\s*(\d{1,2})\s*год\b",
        r"\bмне\s*(\d{1,2})\b",
    ]

    for pattern in age_patterns:
        match = re.search(pattern, text)

        if match:
            age = int(match.group(1))

            if 14 <= age <= 100:
                memory["age"] = age
                break

    # =====================================================
    # 2. ОТБАСЫЛЫҚ ЖАҒДАЙ
    # =====================================================

    if any(
        phrase in text
        for phrase in [
            "ажырасқанмын",
            "ажырастым",
            "ажырасып кеттім",
            "ажырасқаныма",
            "ажырасып жатырмын",
            "разведен",
            "разведён",
            "развелся",
            "развелась",
            "мы развелись",
            "развелись",
        ]
    ):
        memory["marital_status"] = "ажырасқан"

    elif any(
        phrase in text
        for phrase in [
            "үйленгенмін",
            "үйлендім",
            "әйелім бар",
            "отбасылымын",
            "женат",
            "я женат",
        ]
    ):
        memory["marital_status"] = "үйленген"

    elif any(
        phrase in text
        for phrase in [
            "бойдақпын",
            "бойдақ",
            "үйленбегенмін",
            "холост",
            "я холост",
            "не женат",
        ]
    ):
        memory["marital_status"] = "бойдақ"

    # =====================================================
    # 3. БАЛАЛАР
    # =====================================================

    children_patterns = [
        r"\b(\d+)\s*балам\s*бар\b",
        r"\b(\d+)\s*балам\b",
        r"\bбалаларым\s*(\d+)\b",
        r"\bу меня\s*(\d+)\s*дет",
        r"\bу меня\s*(\d+)\s*реб",
    ]

    for pattern in children_patterns:
        match = re.search(pattern, text)

        if match:
            children = int(match.group(1))

            if 1 <= children <= 20:
                memory["children"] = children
                break

    if "children" not in memory:
        for word, number in KZ_NUMBER_WORDS.items():

            patterns = [
                f"{word} балам бар",
                f"{word} балам",
                f"{word} баламын",
            ]

            if any(pattern in text for pattern in patterns):
                memory["children"] = number
                break

    if "children" not in memory:
        for word, number in RU_NUMBER_WORDS.items():

            patterns = [
                f"у меня {word} детей",
                f"у меня {word} ребенка",
                f"у меня {word} ребёнка",
                f"у меня {word} ребенок",
                f"у меня {word} ребёнок",
            ]

            if any(pattern in text for pattern in patterns):
                memory["children"] = number
                break

    # =====================================================
    # 4. ЖҰМЫС / МАНСАП
    # =====================================================

    career_patterns = [
        (
            [
                "жаңа тұрақты жұмыс таптым",
                "тұрақты жұмыс таптым",
                "жаңа жұмысқа кірдім",
                "жұмысқа кірдім",
                "тұрақты жұмысқа орналастым",
                "нашел новую работу",
                "нашёл новую работу",
                "нашла новую работу",
                "устроился на работу",
                "устроилась на работу",
                "теперь работаю",
                "работу нашел",
                "работу нашёл",
            ],
            "тұрақты жұмысы бар",
        ),

        (
            [
                "жұмысым тұрақсыз",
                "жұмыс тұрақсыз",
                "жұмысым тұрақты емес",
                "тұрақсыз жұмыс",
                "работа нестабильная",
                "нестабильная работа",
                "у меня нестабильная работа",
            ],
            "жұмысы тұрақсыз",
        ),

        (
            [
                "жұмыссызбын",
                "жұмыс жоқ",
                "жұмыссыз жүрмін",
                "жұмыстан шығып қалдым",
                "жұмыстан шықтым",
                "жұмыстан айырылдым",
                "без работы",
                "безработный",
                "безработная",
                "потерял работу",
                "потеряла работу",
                "уволился",
                "уволилась",
                "меня уволили",
            ],
            "жұмыссыз",
        ),

        (
            [
                "өз бизнесім бар",
                "бизнесім бар",
                "кәсібім бар",
                "свой бизнес",
                "у меня свой бизнес",
                "я предприниматель",
            ],
            "кәсіпкер",
        ),
    ]

    for phrases, value in career_patterns:
        if any(phrase in text for phrase in phrases):
            memory["career"] = value
            break

    # =====================================================
    # 5. ҚАРЖЫЛЫҚ ЖАҒДАЙ
    # =====================================================

    financial_patterns = [
        (
            [
                "қаржым тұрақталды",
                "ақшам жетіп жүр",
                "қаржылық жағдайым жақсарды",
                "финансовое положение улучшилось",
                "с деньгами стало лучше",
            ],
            "қаржылық жағдайы тұрақты",
        ),

        (
            [
                "ақша жетпейді",
                "ақшам жетпейді",
                "қаржы жетпейді",
                "қаржылық қиындық",
                "финансовые проблемы",
                "денег не хватает",
                "не хватает денег",
            ],
            "қаржылық қиындық бар",
        ),

        (
            [
                "қарызым бар",
                "қарыздарым бар",
                "несием бар",
                "кредитім бар",
                "у меня кредит",
                "у меня кредиты",
                "у меня долг",
                "у меня долги",
            ],
            "қарызы/несиесі бар",
        ),

        (
            [
                "ақшам жоқ",
                "ақша жоқ",
                "денег нет",
                "совсем нет денег",
            ],
            "ақша тапшылығы",
        ),
    ]

    for phrases, value in financial_patterns:
        if any(phrase in text for phrase in phrases):
            memory["financial_status"] = value
            break

    # =====================================================
    # 6. НЕГІЗГІ МАҚСАТ
    # =====================================================

    goal_patterns = [
        (
            [
                "балаларыммен қарым-қатынасты қалпына келтіру",
                "балаларыммен қарым-қатынасымды қалпына келтіру",
                "балаларыммен қайта жақындасу",
                "хочу восстановить отношения с детьми",
                "хочу наладить отношения с детьми",
            ],
            "балаларымен қарым-қатынасты қалпына келтіру",
        ),

        (
            [
                "жұмысымды тұрақтандыру",
                "жұмысымды тұрақты ету",
                "тұрақты жұмыс табу",
                "хочу найти стабильную работу",
                "нужна стабильная работа",
                "моя цель найти стабильную работу",
            ],
            "жұмысын тұрақтандыру",
        ),

        (
            [
                "ақша тапқым келеді",
                "көбірек ақша тапқым келеді",
                "табысымды көбейткім келеді",
                "көбірек табыс тапқым келеді",
                "хочу больше зарабатывать",
                "хочу увеличить доход",
            ],
            "табысын көбейту",
        ),

        (
            [
                "бизнес бастағым келеді",
                "бизнес бастау",
                "кәсіп бастағым келеді",
                "өз бизнесімді бастағым келеді",
                "хочу открыть бизнес",
                "хочу начать свой бизнес",
            ],
            "бизнес бастау",
        ),

        (
            [
                "үй алғым келеді",
                "пәтер алғым келеді",
                "хочу купить дом",
                "хочу купить квартиру",
            ],
            "үй/пәтер алу",
        ),
    ]

    for phrases, value in goal_patterns:
        if any(phrase in text for phrase in phrases):
            memory["main_goal"] = value
            break

    # =====================================================
    # 7. ҚОСЫМША МАҚСАТТАР
    # =====================================================

    goals = []

    if any(
        phrase in text
        for phrase in [
            "өзімді дамыту",
            "өзімді дамытқым келеді",
            "саморазвитие",
            "хочу развиваться",
        ]
    ):
        goals.append("өзін дамыту")

    if any(
        phrase in text
        for phrase in [
            "спортпен айналысқым келеді",
            "спортқа барғым келеді",
            "хочу заниматься спортом",
        ]
    ):
        goals.append("дене дайындығын жақсарту")

    if any(
        phrase in text
        for phrase in [
            "ағылшын үйренгім келеді",
            "хочу выучить английский",
            "хочу улучшить английский",
        ]
    ):
        goals.append("ағылшын тілін жақсарту")

    if goals:
        memory["goals"] = goals

    # =====================================================
    # 8. ӘДЕТТЕР
    # =====================================================

    habits = []

    if any(
        phrase in text
        for phrase in [
            "спортпен айналысамын",
            "спортпен айналысып жүрмін",
            "спортқа барып жүрмін",
            "занимаюсь спортом",
            "хожу в спортзал",
        ]
    ):
        habits.append("спорт")

    if any(
        phrase in text
        for phrase in [
            "ерте тұрамын",
            "ерте тұрып жүрмін",
            "рано встаю",
        ]
    ):
        habits.append("ерте тұру")

    if any(
        phrase in text
        for phrase in [
            "жаттығу жасаймын",
            "жаттығу жасап жүрмін",
            "тренировка жасаймын",
            "тренируюсь",
        ]
    ):
        habits.append("жаттығу")

    if habits:
        memory["habits"] = habits

    # =====================================================
    # 9. МАҢЫЗДЫ ОҚИҒАЛАР
    # =====================================================

    important_events = []

    if any(
        phrase in text
        for phrase in [
            "ажырасқаныма",
            "ажырасып кеттім",
            "ажырасып жатырмын",
            "развелся",
            "развелась",
            "мы развелись",
        ]
    ):
        important_events.append("ажырасу кезеңі")

    if any(
        phrase in text
        for phrase in [
            "жаңа жұмысқа кірдім",
            "жаңа жұмыс таптым",
            "жаңа тұрақты жұмыс таптым",
            "нашел новую работу",
            "нашёл новую работу",
            "устроился на работу",
        ]
    ):
        important_events.append("жаңа жұмыс басталды")

    if any(
        phrase in text
        for phrase in [
            "жұмыстан шықтым",
            "жұмыстан айырылдым",
            "меня уволили",
            "потерял работу",
            "уволился",
        ]
    ):
        important_events.append("жұмысынан айырылу/ауысу")

    if important_events:
        memory["important_events"] = important_events

    # =====================================================
    # 10. НӘТИЖЕ
    # =====================================================

    return memory