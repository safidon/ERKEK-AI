def build_risk_response(risk: str, language: str = "kk") -> str | None:
    """
    Қауіп деңгейіне байланысты арнайы жауап қайтарады.

    None:
        арнайы risk response қажет емес,
        кәдімгі ERKEK AI жауабын жалғастыруға болады.
    """

    if risk == "critical":

        if language == "ru":
            return (
                "Сейчас главное — твоя безопасность.\n\n"
                "Не оставайся один и не принимай необратимых решений "
                "в этом состоянии. Свяжись прямо сейчас с человеком, "
                "которому доверяешь, и скажи ему прямо, что тебе тяжело.\n\n"
                "Если есть непосредственная опасность для твоей жизни — "
                "обратись в экстренную службу или ближайшее медицинское учреждение.\n\n"
                "Сейчас не нужно решать всю жизнь. "
                "Первая задача — безопасно пройти ближайшее время."
            )

        return (
            "Қазір бірінші мәселе — сенің қауіпсіздігің.\n\n"
            "Жалғыз қалма және осы күйде қайтымсыз шешім қабылдама. "
            "Дәл қазір сенетін адамыңа хабарласып, жағдайыңның ауыр екенін ашық айт.\n\n"
            "Егер өміріңе тікелей қауіп бар болса — "
            "жедел қызметке немесе жақын медициналық мекемеге жүгін.\n\n"
            "Қазір бүкіл өміріңді шешудің қажеті жоқ. "
            "Бірінші міндет — алдағы уақытты қауіпсіз өткізу."
        )

    if risk == "high":

        if language == "ru":
            return (
                "Сейчас важно не действовать на эмоциях.\n\n"
                "Отойди от человека, на которого злишься, "
                "и не вступай с ним в конфликт. Убери от себя предметы, "
                "которыми можно причинить вред.\n\n"
                "Дай себе время выйти из острого состояния. "
                "Если чувствуешь, что можешь потерять контроль — "
                "обратись за помощью к близкому человеку или экстренной службе."
            )

        return (
            "Қазір эмоциямен әрекет етпеу маңызды.\n\n"
            "Ашуланып тұрған адамыңнан уақытша алыста және жанжалға кіріспе. "
            "Зиян келтіруге болатын заттарды өзіңнен алыстат.\n\n"
            "Өткір эмоция басылғанша өзіңе уақыт бер. "
            "Егер бақылауды жоғалтып алуың мүмкін екенін сезсең — "
            "жақын адамыңнан немесе жедел қызметтен көмек сұра."
        )

    return None