def _compile(pattern: str) -> re.Pattern:
    allow_suffix = pattern.endswith("*")
    words = pattern.rstrip("*").split()
    # Сөздер арасындағы бос орын — бір немесе бірнеше бос орын.
    core = r"\s+".join(re.escape(word) for word in words)
    return re.compile(
        r"(?<!\w)" + core + ("" if allow_suffix else r"(?!\w)")
    )


_LEVELS = [
    ("critical", [_compile(p) for p in CRITICAL_PATTERNS]),
    ("high", [_compile(p) for p in HIGH_PATTERNS]),
    ("medium", [_compile(p) for p in MEDIUM_PATTERNS]),
]


def _normalize(message: str) -> str:
    text = message.lower().replace("ё", "е")
    return " ".join(text.split())


def detect_risk(message: str) -> str:
    """
    Пайдаланушы хабарламасындағы қауіп деңгейін анықтайды.
    Ең қауіпті деңгейден бастап тексеріледі.
    """

    text = _normalize(message)

    for level, patterns in _LEVELS:
        if any(p.search(text) for p in patterns):
            return level

    return "low"
