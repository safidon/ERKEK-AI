def detect_risk(message: str) -> str:
    """
    Пайдаланушы хабарламасындағы қауіп деңгейін анықтайды.

    Деңгейлер:
    - low
    - medium
    - high
    - critical
    """

    text = message.lower().strip()

    # ==========================================
    # 1. CRITICAL — ӨЗІНЕ ЗИЯН КЕЛТІРУ ҚАУПІ
    # ==========================================

    critical_patterns = [
        # Қазақша
        "өлгім келеді",
        "өзімді өлтіремін",
        "өзімді өлтіргім келеді",
        "өмір сүргім келмейді",
        "суицид",
        "асылып қалам",
        "асылып өлгім келеді",
        "бәрін бітіргім келеді",

        # Орысша
        "хочу умереть",
        "убью себя",
        "хочу убить себя",
        "не хочу жить",
        "суицид",
        "покончу с собой",
        "хочу покончить с собой"
    ]

    # ==========================================
    # 2. HIGH — БАСҚА АДАМҒА ЗИЯН КЕЛТІРУ ҚАУПІ
    # ==========================================

    high_patterns = [
        # Қазақша
        "оны өлтіремін",
        "сені өлтіремін",
        "өлтіріп тастаймын",
        "ұрып тастаймын",
        "пышақтаймын",
        "кек аламын",

        # Орысша
        "я его убью",
        "я ее убью",
        "я тебя убью",
        "убью его",
        "убью ее",
        "зарежу",
        "отомщу"
    ]

    # ==========================================
    # 3. MEDIUM — ЭМОЦИЯЛЫҚ БАҚЫЛАУДЫ ЖОҒАЛТУ
    # ==========================================

    medium_patterns = [
        # Қазақша
        "шыдай алмаймын",
        "өзімді ұстай алмаймын",
        "не істерімді білмеймін",
        "бәрінен шаршадым",
        "қатты ашулымын",

        # Орысша
        "не могу больше",
        "не могу себя контролировать",
        "не знаю что делать",
        "все надоело",
        "очень зол"
    ]

    # ==========================================
    # 4. ТЕКСЕРУ
    # Ең қауіпті деңгейден бастаймыз
    # ==========================================

    for pattern in critical_patterns:
        if pattern in text:
            return "critical"

    for pattern in high_patterns:
        if pattern in text:
            return "high"

    for pattern in medium_patterns:
        if pattern in text:
            return "medium"

    return "low"