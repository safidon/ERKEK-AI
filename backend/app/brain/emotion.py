def detect_emotion(message: str) -> int:
    """
    Хабарламадағы эмоционалдық кернеуді 0-100 аралығында есептейді.
    """

    text = message.lower().strip()

    stress = 0

    # ==========================================
    # 1. МҰҢ / УАЙЫМ / ҚОРҚЫНЫШ
    # ==========================================

    sadness_words = [
        "кетіп",
        "ажырас",
        "жыла",
        "ауыр",
        "жалғыз",
        "қорқам",
        "шаршадым",
        "үміт жоқ",
        "болмайды",
        "уайым",
        "алаң",
        "сағындым",
        "сағынамын",
        "қиналып",
        "көңілім жоқ",

        # Орысша
        "пережива",
        "тревож",
        "груст",
        "одинок",
        "боюсь",
        "скучаю",
        "тяжело"
    ]

    # ==========================================
    # 2. КҮШТІ ЭМОЦИЯ
    # ==========================================

    strong_emotion_words = [
        "қатты уайым",
        "қатты алаң",
        "қатты сағын",
        "өте қиын",
        "өте ауыр",
        "шыдай алмай",
        "қатты қорқ",

        # Орысша
        "сильно пережива",
        "очень тревож",
        "очень тяжело",
        "сильно скуча",
        "не могу больше"
    ]

    # ==========================================
    # 3. АШУ
    # ==========================================

    anger_words = [
        "ашулымын",
        "жек көрем",
        "ыза",
        "ұрамын",
        "қатты ашул",

        # Орысша
        "злюсь",
        "ненавижу",
        "в ярости"
    ]

    # ==========================================
    # 4. ЕСЕПТЕУ
    # ==========================================

    for word in sadness_words:
        if word in text:
            stress += 20

    for word in strong_emotion_words:
        if word in text:
            stress += 30

    for word in anger_words:
        if word in text:
            stress += 25

    # ==========================================
    # 5. ШЕКТЕУ
    # ==========================================

    return min(stress, 100)