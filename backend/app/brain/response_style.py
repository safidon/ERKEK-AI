def detect_response_style(
    message: str,
    category: str,
    risk: str,
    emotion: int
) -> str:
    """
    ERKEK AI жауабының көлемін анықтайды.

    Нәтиже:
    - short
    - normal
    - deep
    """

    text = message.strip()

    # ==========================================
    # 1. ҚАУІПТІ ЖАҒДАЙ
    # ==========================================

    if risk in ["high", "critical"]:
        return "normal"

    # ==========================================
    # 2. ПАЙДАЛАНУШЫ ӨЗІ ТОЛЫҚ ТАЛДАУ СҰРАСА
    # ==========================================

    deep_words = [
        # Қазақша
        "толық талда",
        "толық жоспар",
        "егжей-тегжейлі",
        "нақты жоспар құр",
        "жан-жақты",
        "толық түсіндір",

        # Орысша
        "подробно",
        "полный план",
        "подробный план",
        "детально",
        "разбери подробно",
        "полный анализ"
    ]

    if any(word in text.lower() for word in deep_words):
        return "deep"

    # ==========================================
    # 3. ӨТЕ ҚЫСҚА ХАБАРЛАМА
    # ==========================================

    if len(text) <= 80:
        return "short"

    # ==========================================
    # 4. КҮШТІ ЭМОЦИЯ
    # ==========================================

    if emotion >= 60:
        return "normal"

    # ==========================================
    # 5. КҮРДЕЛІ КАТЕГОРИЯЛАР
    # ==========================================

    complex_categories = [
        "relationship",
        "finance",
        "fatherhood"
    ]

    if category in complex_categories and len(text) >= 250:
        return "deep"

    # ==========================================
    # 6. ӘДЕПКІ РЕЖИМ
    # ==========================================

    return "normal"


def build_response_style_prompt(
    style: str,
    language: str
) -> str:
    """
    Таңдалған режимді AI prompt-қа айналдырады.
    """

    if language == "ru":

        prompts = {

            "short": """
РЕЖИМ ОТВЕТА: КОРОТКИЙ.

Ответ должен быть кратким и практичным.

Правила:
- примерно 150–300 слов;
- не пытайся решить всю жизнь пользователя одним ответом;
- не создавай планы на 3–12 месяцев без необходимости;
- максимум 3 конкретных действия;
- максимум 1–2 уточняющих вопроса;
- не повторяй одну мысль несколько раз;
- используй структуру ERKEK AI;
- фокус на следующем правильном шаге.
""",

            "normal": """
РЕЖИМ ОТВЕТА: ОБЫЧНЫЙ.

Правила:
- примерно 300–600 слов;
- кратко разберись в ситуации;
- дай 3–5 конкретных действий;
- не перегружай пользователя;
- долгосрочный план давай только если он действительно нужен;
- максимум 2–3 уточняющих вопроса;
- не повторяй информацию из Memory без необходимости.
""",

            "deep": """
РЕЖИМ ОТВЕТА: ГЛУБОКИЙ.

Пользователь просит подробный анализ или ситуация действительно сложная.

Правила:
- примерно 600–1000 слов;
- можно дать краткосрочный и среднесрочный план;
- используй конкретные измеримые действия;
- не добавляй объем ради объема;
- избегай повторов;
- даже глубокий ответ должен оставаться практичным.
"""
        }

    else:

        prompts = {

            "short": """
ЖАУАП РЕЖИМІ: ҚЫСҚА.

Жауап қысқа және практикалық болсын.

Ережелер:
- шамамен 150–300 сөз;
- бір жауапта пайдаланушының бүкіл өмірін шешуге тырыспа;
- қажет болмаса 3–12 айлық үлкен жоспар құрма;
- максимум 3 нақты әрекет бер;
- максимум 1–2 нақтылау сұрағын қой;
- бір ойды бірнеше рет қайталама;
- ERKEK AI құрылымын сақта;
- келесі дұрыс қадамға назар аудар.
""",

            "normal": """
ЖАУАП РЕЖИМІ: ҚАЛЫПТЫ.

Ережелер:
- шамамен 300–600 сөз;
- жағдайды қысқаша талда;
- 3–5 нақты әрекет бер;
- пайдаланушыны ақпаратпен тұншықтырма;
- ұзақ мерзімді жоспарды тек шынымен қажет болса бер;
- максимум 2–3 нақтылау сұрағын қой;
- Memory-дегі ақпаратты қажетсіз қайталама.
""",

            "deep": """
ЖАУАП РЕЖИМІ: ТЕРЕҢ.

Пайдаланушы толық талдау сұрады немесе жағдай күрделі.

Ережелер:
- шамамен 600–1000 сөз;
- қысқа және орта мерзімді жоспар беруге болады;
- нақты әрі өлшенетін әрекеттер қолдан;
- тек көлем үшін артық мәтін қоспа;
- қайталанудан аулақ бол;
- терең жауаптың өзі практикалық болуы керек.
"""
        }

    return prompts.get(
        style,
        prompts["normal"]
    )