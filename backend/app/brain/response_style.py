def detect_response_style(
    message: str,
    category: str,
    risk: str,
    emotion: int
) -> str:
    """
    ERKEK AI жауабының тереңдігі мен көлемін анықтайды.

    Нәтиже:
    - short
    - normal
    - deep
    """

    text = message.strip()
    text_lower = text.lower()

    # ==========================================
    # 1. ҚАУІПТІ ЖАҒДАЙ
    # ==========================================

    if risk in ["high", "critical"]:
        return "normal"

    # ==========================================
    # 2. ПАЙДАЛАНУШЫ ТОЛЫҚ ТАЛДАУ СҰРАСА
    # ==========================================

    deep_words = [
        # Қазақша
        "толық талда",
        "толық жоспар",
        "егжей-тегжейлі",
        "нақты жоспар құр",
        "жан-жақты",
        "толық түсіндір",

        # Орысша
        "подробно",
        "полный план",
        "подробный план",
        "детально",
        "разбери подробно",
        "полный анализ"
    ]

    if any(
        word in text_lower
        for word in deep_words
    ):
        return "deep"

    # ==========================================
    # 3. ӨТЕ ҚЫСҚА ХАБАРЛАМА
    # ==========================================

    if len(text) <= 80:
        return "short"

    # ==========================================
    # 4. КҮШТІ ЭМОЦИЯ
    # ==========================================

    if emotion >= 60:
        return "normal"

    # ==========================================
    # 5. КҮРДЕЛІ КАТЕГОРИЯ + ҰЗЫН ХАБАРЛАМА
    # ==========================================

    complex_categories = {
        "relationship",
        "finance",
        "fatherhood"
    }

    if (
        category in complex_categories
        and len(text) >= 250
    ):
        return "deep"

    # ==========================================
    # 6. ӘДЕПКІ РЕЖИМ
    # ==========================================

    return "normal"


def build_response_style_prompt(
    style: str,
    language: str
) -> str:
    """
    Жауаптың көлемі мен тереңдігіне арналған
    қысқа instruction қайтарады.
    """

    if language == "ru":

        prompts = {

            "short": """
РЕЖИМ: КОРОТКИЙ.

- 150–300 слов.
- Максимум 3 конкретных действия.
- Максимум 1–2 уточняющих вопроса.
- Не создавай долгосрочный план без необходимости.
""",

            "normal": """
РЕЖИМ: ОБЫЧНЫЙ.

- 300–600 слов.
- Дай 3–5 конкретных действий.
- Максимум 2–3 уточняющих вопроса.
- Долгосрочный план добавляй только при необходимости.
""",

            "deep": """
РЕЖИМ: ГЛУБОКИЙ.

- 600–1000 слов.
- Можно использовать краткосрочный и среднесрочный план.
- Добавляй измеримые действия и этапы.
"""
        }

    else:

        prompts = {

            "short": """
ЖАУАП РЕЖИМІ: ҚЫСҚА.

- 150–300 сөз.
- Максимум 3 нақты әрекет.
- Максимум 1–2 нақтылау сұрағы.
- Қажет болмаса ұзақ мерзімді жоспар құрма.
""",

            "normal": """
ЖАУАП РЕЖИМІ: ҚАЛЫПТЫ.

- 300–600 сөз.
- 3–5 нақты әрекет бер.
- Максимум 2–3 нақтылау сұрағы.
- Ұзақ мерзімді жоспарды тек қажет болса қос.
""",

            "deep": """
ЖАУАП РЕЖИМІ: ТЕРЕҢ.

- 600–1000 сөз.
- Қысқа және орта мерзімді жоспар қолдануға болады.
- Нақты және өлшенетін әрекеттер бер.
"""
        }

    return prompts.get(
        style,
        prompts["normal"]
    )